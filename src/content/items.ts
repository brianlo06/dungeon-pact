/**
 * A supply is an item whose whole value is one action. `trigger: "use"` is
 * never fired by the trigger loop, so a supply has no passive: carrying it
 * grants `use` as an ability, and spending that ability spends the supply.
 */
const supply = (
  id: string,
  name: string,
  rarity: ItemDef["rarity"],
  tags: string[],
  clue: string,
  price: number,
  use: Ability,
): ItemDef => ({
  id,
  name,
  rarity,
  slot: "supply",
  tags,
  description: use.description,
  clue,
  cursed: false,
  trigger: "use",
  effects: [],
  use,
  target: "self",
  price,
});
const action = (
  id: string,
  name: string,
  description: string,
  target: Ability["target"],
  effects: Ability["effects"],
  speed = 8,
): Ability => ({
  id,
  name,
  description,
  target,
  effects,
  cost: 0,
  speed,
  cooldown: 0,
});
