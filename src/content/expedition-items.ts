import type { ItemDef, Effect } from "../shared/model";

// Modular art families are intentionally shared; each definition owns its
// rules and presentation metadata, so final artwork can be replaced in data.
function gear(
  id: string,
  name: string,
  slot: "weapon" | "armor" | "relic",
  trigger: ItemDef["trigger"],
  target: ItemDef["target"],
  effects: Effect[],
  description: string,
  price: number,
  asset: string,
  accent: string,
  reaction?: NonNullable<ItemDef["visual"]>["reaction"],
): ItemDef {
  return {
    id,
    name,
    slot,
    trigger,
    target,
    effects,
    description,
    price,
    rarity: price >= 180 ? "Epic" : price >= 110 ? "Rare" : "Common",
    tags: [
      "Foundry",
      slot === "weapon" ? "Assault" : slot === "armor" ? "Guardian" : "Utility",
    ],
    clue: `A foundry stamp reads: ${name}.`,
    cursed: false,
    visual: {
      slot,
      accent,
      reaction,
      replacesBaseWeapon: slot === "weapon",
      attachments: [
        {
          anchor:
            slot === "weapon"
              ? "mainHand"
              : slot === "armor"
                ? "torso"
                : "waist",
          layer:
            slot === "weapon" ? "weapon" : slot === "armor" ? "body" : "front",
          asset,
        },
      ],
    },
  };
}
const mark = (
  status: "weak" | "vulnerable" | "marked" | "barrier" | "regen",
  stacks: number,
  duration: number,
): Effect => ({ kind: "status", status, stacks, duration });
