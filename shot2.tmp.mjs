import { chromium } from "@playwright/test";
const OUT = process.argv[2];
const B = "http://127.0.0.1:5399/dev/bosses.html?viewport=fit&party=4&motion=1";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const hide = () => p.addStyleTag({ content: ".preview-toolbar{display:none!important}" });
await p.goto(`${B}&stage=opening`);
await p.locator(".battle").waitFor(); await hide();
await p.waitForTimeout(1900);
await p.screenshot({ path: `${OUT}/m2-intro.png` });
await p.waitForTimeout(2200);
await p.screenshot({ path: `${OUT}/m2-after-intro.png` });
await b.close();
